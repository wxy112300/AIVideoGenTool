export function icon(name: string, className = ""): string {
  return `<i data-lucide="${name}" class="ui-icon ${className}" aria-hidden="true"></i>`;
}

export function renderIcons(root: Element | Document | DocumentFragment): void {
  const pending = root.querySelectorAll<HTMLElement>("i[data-lucide]");
  if (!pending.length) return;
  pending.forEach((element) => element.setAttribute("data-lucide-pending", element.getAttribute("data-lucide")!));
  createIcons({
    icons: lucideIconSet,
    root,
    nameAttr: "data-lucide-pending",
    attrs: {
      "stroke-width": "1.8",
    }
  });
  root.querySelectorAll("svg[data-lucide-pending]").forEach((element) => element.removeAttribute("data-lucide-pending"));
}
