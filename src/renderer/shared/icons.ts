export function icon(name: string, className = ""): string {
  return `<i data-lucide="${name}" class="ui-icon ${className}" aria-hidden="true"></i>`;
}

export function renderIcons(root: Element): void {
  createIcons({
    icons: lucideIconSet,
    root,
    attrs: {
      "stroke-width": "1.8"
    }
  });
}
