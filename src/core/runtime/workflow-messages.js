const catalogs = {
    "zh-CN": zhCN,
    "zh-TW": zhTWWorkflowMessages,
    "en-US": enUS
};
export function workflowMessage(key, params = {}, locale = "zh-CN") {
    const template = catalogs[locale][key] ?? zhCN[key];
    return template.replace(/\{([A-Za-z0-9_.-]+)\}/gu, (match, name) => {
        const value = params[name];
        return value == null ? match : String(value);
    });
}
