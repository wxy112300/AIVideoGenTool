  it("ignores an older inspection when switching A to B and back to A", async () => {
    const h = journey = await createJourney({ inputMode: "video", modelId: "minimax_h3_continuum" });
    let finishFirst!: (value: { route: "bootstrap"; status: "invalid"; reason: string }) => void;
    const inspect = h.application.inspectVideoExtensionSource;
    inspect.mockImplementationOnce(() => new Promise(resolve => { finishFirst = resolve; }))
      .mockResolvedValueOnce({ route: "bootstrap", status: "invalid", reason: "B is invalid" })
      .mockResolvedValueOnce({ route: "bootstrap", status: "available" });
    h.coordinator.patchDraft({ sourceVideoPath: "source.mp4", sourceWidth: 1280, sourceHeight: 720,
      sourceVideoDuration: 8, h3ContinuumArtifactPath: "A.safetensors" }); h.render();
    h.coordinator.patchDraft({ h3ContinuumArtifactPath: "B.safetensors" }); h.render(); await settle();
    h.coordinator.patchDraft({ h3ContinuumArtifactPath: "A.safetensors" }); h.render(); await settle();
    finishFirst({ route: "bootstrap", status: "invalid", reason: "stale A must be ignored" }); await settle();
    expect(inspect).toHaveBeenCalledTimes(3);
    expect(h.coordinator.renderPage()).not.toContain("stale A must be ignored");
  });
  it("keeps native duration locked until explicit unlock and keeps a continuous resolution drag mounted", async () => {
    const h = journey = await createJourney();
    h.input("#duration-number", "30", "change");
    expect(h.state().draft.duration).toBe(15.1);
    expect(h.element<HTMLSelectElement>("#generation-mode").value).toBe("native");
    h.input("#generation-mode", "unlocked", "change"); h.input("#duration-number", "30", "change");
    expect(h.state().draft.duration).toBe(30);
    h.element("#video-resolution-custom").click();
    const slider = h.element<HTMLInputElement>('[data-custom-resolution-panel] input[type=range]');
    const changes: MutationRecord[] = [];
    const observer = new MutationObserver(records => changes.push(...records));
    observer.observe(slider, { attributes: true, attributeFilter: ["min", "max", "step"] });
    for (const resolution of [784, 832, 848, 864, 992, 1072]) {
      h.input('[data-custom-resolution-panel] input[type=range]', String(resolution));
      expect(h.state().draft.resolution).toBe(resolution);
      expect(h.element<HTMLInputElement>('[data-custom-resolution-panel] input[type=range]')).toBe(slider);
    }
    Object.assign(slider, { setPointerCapture: vi.fn(), hasPointerCapture: () => true, releasePointerCapture: vi.fn() });
    vi.spyOn(slider, "getBoundingClientRect").mockReturnValue({ left: 0, width: 118 } as DOMRect);
    const pointer = (type: string, resolution: number) => {
      const event = new MouseEvent(type, { clientX: 9 + (resolution - 256) / 824 * 100, button: 0, bubbles: true, cancelable: true });
      Object.defineProperty(event, "pointerId", { value: 7 }); return event;
    };
    slider.dispatchEvent(pointer("pointerdown", 992)); slider.dispatchEvent(pointer("pointermove", 832));
    expect(h.state().draft.resolution).toBe(832);
    slider.dispatchEvent(pointer("pointerup", 832)); slider.dispatchEvent(pointer("pointermove", 992));
    expect(h.state().draft.resolution).toBe(832);
    await settle(); observer.disconnect(); expect(changes).toHaveLength(0);
  });
